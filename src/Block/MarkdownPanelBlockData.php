namespace Middag\Ui\Block;

/**
 * The `data` of a `markdown_panel` block: markdown `content` and an optional
 * `maxHeight` in pixels.
 *
 * A schema-only value shape (no instances): it types block data for schema
 * consumers. {@see BlockBuilder} keeps taking plain arrays.
 *
 * @api
 */
final class MarkdownPanelBlockData
{
    private function __construct() {}

    /** @return array<string, mixed> */
    public static function jsonSchema(): array
    {
        return [
            'type' => 'object',
            'required' => ['content'],
            'properties' => [
                'content' => ['type' => 'string'],
                'maxHeight' => ['type' => 'number'],
            ],
            'additionalProperties' => false,
        ];
    }
}
